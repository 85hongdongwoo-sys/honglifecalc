def ann(avg,yrs,adj=0):
    avg=min(avg,45800); A=avg*yrs*0.00775+3000; B=avg*yrs*0.0155; base=max(A,B)
    return rnd(A),rnd(B),('第一式' if A>=B else '第二式'),rnd(base*(1+adj))

